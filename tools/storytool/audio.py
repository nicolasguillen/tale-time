"""`story assets`, narration part: writes the narration requests. Each story gets one REQUESTED_AUDIO.md per language,
inside the folder that language's clips go into (`audio/<lang>/`), and written in that language for its narrator:
the voice, how to deliver, the technical spec, who's in the story and every clip with its exact script and direction.
The one at the repository root is the index, in English: each story's status per language, with a link to its file,
and the narrators.

This project never generates audio: no text-to-speech, no voice models, no synthesized speech. Each clip is requested
here with its exact script, voice direction and technical spec, recorded or produced outside the repo, and dropped into
the folder named in its entry. Until then the app reads without narration.
"""
import os
from dataclasses import dataclass
from pathlib import Path

from . import graph
from .audio_text import TEXT
from .check import word_count
from .repo import (REQUESTED_ASSETS, REQUESTED_AUDIO, ROOT, STORIES, VOICE, audio_dir, find_audio, has_story,
                   load_json, load_story, story_ids, translation_file)

HEADER = ("<!-- Generated by `story assets`. Edit the sources (voice.json, story/<lang>.json, bible.json, shots.json, "
          "translations/), not this file. -->")
STORY_HEADER = ("<!-- Generated by `story assets`. Edit the sources (this story's story/<lang>.json, bible.json, "
                "shots.json and translations/, or content/style/voice.json), not this file. -->")
GENERATED = "<!-- Generated by `story assets`."
# The name of the requests file: the index at the root, and one in every audio/<lang>/ folder.
FILE = REQUESTED_AUDIO.name
KINDS = ["title", "page", "question", "option", "ending"]
# Seconds of silence around each clip (the technical spec), added to the reading time in the estimates.
PADDING = 0.8


@dataclass(frozen=True)
class Clip:
    id: str
    kind: str  # one of KINDS
    script: str
    node: str | None = None
    option: int | None = None


def clips(story: dict) -> list[Clip]:
    """Every clip of a story in one language (its story/<lang>.json), in reading order. The ids match
    check.audio_clips()."""
    out = [Clip("title", "title", story["title"])]
    for nid, node in story["nodes"].items():
        k = graph.kind(node)
        out.append(Clip(nid, "page", node["text"], nid))
        if k == graph.FORK:
            out.append(Clip(f"{nid}-q", "question", node["question"], nid))
            for i, option in enumerate(node["options"]):
                out.append(Clip(f"{nid}-{'ab'[i]}", "option", option["label"], nid, i))
        if k == graph.ENDING:
            out.append(Clip(f"{nid}-end", "ending", node["ending"]["title"], nid))
    return out


def seconds(script: str, words_per_minute: int) -> float:
    return word_count(script) * 60 / words_per_minute + PADDING


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else path.as_posix()


def _link(target: Path, start: Path) -> str:
    return Path(os.path.relpath(target, start)).as_posix()


def _quote(text: str) -> str:
    return "\n".join(f"> {line}" if line else ">" for line in text.splitlines())


class Words:
    """The wording of one language's file (audio_text.py), with its number and duration formats."""

    def __init__(self, lang: str):
        self.lang = lang
        self.t = TEXT[lang]

    def __getitem__(self, key: str):
        return self.t[key]

    def number(self, n: int) -> str:
        sep = self.t["thousands"]
        if sep == " " and n < 10_000:  # Spanish groups digits only from five on: 1477, 12 345.
            return str(n)
        return f"{n:,}".replace(",", sep)

    def duration(self, total: float) -> str:
        if total < 90:
            return self.t["seconds"].format(n=max(1, round(total)))
        return self.t["minutes"].format(n=round(total / 60))

    def language(self, lang: str) -> str:
        return f"{self.t['languages'].get(lang, lang)} (`{lang}`)"


class Story:
    def __init__(self, folder: Path):
        self.folder = folder
        self.languages = load_story(folder)  # language -> its story/<lang>.json, the first language first
        self.bible = load_json(folder / "bible.json")
        shots_file = folder / "shots.json"
        shots = load_json(shots_file) if shots_file.is_file() else {"images": []}
        self.shot = {s["id"]: s for s in shots["images"]}
        self._sheets: dict[str, dict | None] = {}

    @property
    def first(self) -> str:
        return next(iter(self.languages))

    def text(self, lang: str) -> dict:
        """The story in one language: its story/<lang>.json."""
        return self.languages[lang]

    def audio_dir(self, lang: str) -> Path:
        return audio_dir(self.folder, lang)

    def requests_file(self, lang: str) -> Path:
        return self.audio_dir(lang) / FILE

    def delivered(self, lang: str, clip_id: str) -> Path | None:
        return find_audio(self.audio_dir(lang), clip_id)

    def translation(self, lang: str) -> dict | None:
        """The translation sheet of a language after the first, or None (the first, or not translated yet)."""
        if lang not in self._sheets:
            path = translation_file(self.folder, lang)
            self._sheets[lang] = load_json(path) if lang != self.first and path.is_file() else None
        return self._sheets[lang]

    def requested(self, voice: dict) -> list[str]:
        """The languages whose narration can be requested: a narrator, the wording, and a sheet after the first."""
        return [lang for lang in self.languages
                if lang in voice["narrators"] and lang in TEXT
                and (lang == self.first or self.translation(lang) is not None)]

    def draft(self, lang: str) -> bool:
        sheet = self.translation(lang)
        return sheet is not None and sheet["status"] != "approved"

    def cast(self, lang: str) -> list[dict]:
        """Who's in the story, with the name, pronunciation, personality and refrain the language's narrator uses."""
        sheet = self.translation(lang)
        out = []
        for c in self.bible.get("cast", []) + self.bible.get("extras", []) + self.bible.get("props", []):
            if sheet is not None:
                c = {"id": c["id"], **sheet["cast"].get(c["id"], {"name": c.get("name", c["id"])})}
            out.append(c)
        return out

    def tone(self, lang: str) -> list[str]:
        sheet = self.translation(lang)
        return sheet["tone"] if sheet else self.bible["tone"]

    def pitch(self, lang: str) -> str:
        sheet = self.translation(lang)
        return sheet["pitch"] if sheet else self.bible["pitch"]

    def mood(self, lang: str, image_id: str) -> str | None:
        sheet = self.translation(lang)
        if sheet is not None:
            return sheet["moods"].get(image_id)
        return self.shot.get(image_id, {}).get("mood")


def _ready(story_id: str) -> bool:
    """A story's narration is requested once it has its text (step 3)."""
    folder = STORIES / story_id
    return (folder / "bible.json").is_file() and has_story(folder)


def _counts(s: Story, lang: str) -> dict[str, list[int]]:
    counts = {k: [0, 0] for k in KINDS}
    for clip in clips(s.text(lang)):
        counts[clip.kind][1] += 1
        counts[clip.kind][0] += s.delivered(lang, clip.id) is not None
    return counts


def _status_cells(s: Story, lang: str) -> str:
    counts = _counts(s, lang)
    done, total = sum(v[0] for v in counts.values()), sum(v[1] for v in counts.values())
    return " | ".join(f"{counts[k][0]}/{counts[k][1]}" for k in KINDS) + f" | **{done}/{total}**"


# The index at the root ----------------------------------------------------------------------------------------------

def render(voice: dict | None = None, stories: list[Story] | None = None) -> str:
    """The index at the root, in English. Each story's clips are in its own files, rendered by render_story()."""
    voice = voice or load_json(VOICE)
    if stories is None:
        stories = [Story(STORIES / sid) for sid in story_ids() if _ready(sid)]
    waiting = [sid for sid in story_ids() if not _ready(sid)]
    en = Words("en")
    out = [HEADER, "", "# Requested audio", ""]
    out += [
        "Every narration clip the app needs. **No audio in this project is generated: no text-to-speech and no "
        "voice models run in the repo or the pipeline.** Each clip is recorded or produced outside the repo and "
        "dropped into the folder named in its request. Until a story's clips arrive, the app shows its text without "
        "narration.",
        "",
        f"**Each story has one file per language, inside the folder its clips go into** "
        f"(`content/stories/<id>/audio/<lang>/{FILE}`, linked below). Each is written in its own language, for that "
        "language's narrator, and is complete on its own: the narrator's voice, how to deliver, the technical spec, "
        "who's in the story, and every clip with its exact script and direction. This file is only the index.",
        "",
        "This file is generated. To change a request, edit the narrators in `content/style/voice.json`, the words in "
        "the story's `story/<lang>.json`, names and personalities in its `bible.json` (the first language) or its "
        "`translations/<lang>.json` (the others), then run `cd tools && uv run story assets`. Run it again after "
        "delivering files, and the ⬜ entries turn ✅.",
        "",
        "## Status",
        "",
        "| Story | Language | Text | Title | Pages | Questions | Choice labels | Ending titles | Total |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    missing = []
    for s in stories:
        requested = s.requested(voice)
        for lang in s.languages:
            if lang not in requested:
                missing.append(f"*{s.text(s.first)['title']}* in `{lang}`")
                continue
            text = "first" if lang == s.first else "draft translation" if s.draft(lang) else "translation"
            link = _link(s.requests_file(lang), ROOT)
            out.append(f"| [{s.text(lang)['title']}]({link}) | {lang} | {text} | {_status_cells(s, lang)} |")
    out.append("")
    if missing:
        out += [f"Not requested yet, waiting for a translation sheet or a narrator (`uv run story check`): "
                f"{', '.join(missing)}.", ""]
    if waiting:
        names = ", ".join(f"*{next(iter(load_json(STORIES / sid / 'bible.json')['title'].values()))}*"
                          if (STORIES / sid / "bible.json").is_file() else f"`{sid}`" for sid in waiting)
        out += [f"Not requested yet, waiting for the text (step 3): {names}.", ""]
    out += [
        "## Narrators",
        "",
        "One narrator per language, the same for every story in it. Each is described in its own language in "
        "`content/style/voice.json`, and in full at the top of every file in that language.",
        "",
        "| Language | Narrator | Status |",
        "|---|---|---|",
    ]
    for lang, narrator in voice["narrators"].items():
        out.append(f"| {en.language(lang)} | {narrator['name']} | {en['status'][narrator['status']]} |")
    pace = ", ".join(f"{en['bands'].get(band, band)}: about {wpm}" for band, wpm in voice["pace"].items())
    out += ["", f"Every narrator keeps the same pace, in words per minute: {pace}. The app paces a story without "
                "narration at the same speed.", ""]
    return "\n".join(out).rstrip() + "\n"


# One story in one language ------------------------------------------------------------------------------------------

def render_story(s: Story, lang: str | None = None, voice: dict | None = None) -> str:
    """One story's requests file in one language, inside its audio/<lang>/ folder and written in that language."""
    voice = voice or load_json(VOICE)
    lang = lang or s.first
    w = Words(lang)
    story = s.text(lang)
    title = story["title"]
    here = s.audio_dir(lang)
    language = w["languages"].get(lang, lang)
    out = [STORY_HEADER, "", f"# {w['title'].format(title=title, language=language)}", ""]
    out += [w["intro"].format(title=title, language=language), ""]
    if s.draft(lang):
        out += [w["draft"].format(language=language, lang=lang), ""]
    sources = (w["sources-first"] if lang == s.first
               else w["sources-translation"].format(lang=lang, language=language))
    out += [w["generated"].format(lang=lang, sources=sources, assets=_link(s.folder / REQUESTED_ASSETS.name, here),
                                  index=_link(REQUESTED_AUDIO, here)), ""]
    out += [f"| {' | '.join(w['columns'])} |", "|---|---|---|---|---|---|", f"| {_status_cells(s, lang)} |", ""]

    band = story["ageBand"]
    wpm = voice["pace"][band]
    all_clips = clips(story)
    words = sum(word_count(c.script) for c in all_clips)
    chars = sum(len(c.script) for c in all_clips)
    total = sum(seconds(c.script, wpm) for c in all_clips)
    out += [s.pitch(lang), ""]
    out += [
        f"- **{w['folder']}:** `{_rel(here)}/`",
        f"- **{w['pace']}:** {w['pace-value'].format(wpm=wpm, band=w['bands'].get(band, band))}",
        f"- **{w['tone']}:** {', '.join(s.tone(lang))}.",
        f"- **{w['script']}:** " + w["script-value"].format(clips=len(all_clips), words=w.number(words),
                                                            chars=w.number(chars), duration=w.duration(total)),
        "",
    ]
    out += _render_narrator(w, voice, lang)
    out += _render_delivery(w)
    out += _render_cast(s, w, lang)
    out += [f"## {w['clips']}", "", w["clips-intro"], ""]
    narrator = voice["narrators"][lang]
    for clip in all_clips:
        out += _render_clip(s, w, lang, clip, narrator, wpm)
    return "\n".join(out).rstrip() + "\n"


def _render_narrator(w: Words, voice: dict, lang: str) -> list[str]:
    narrator = voice["narrators"][lang]
    out = [f"## {w['narrator'].format(name=narrator['name'], status=w['status'][narrator['status']])}", "",
           narrator["summary"], ""]
    for key, label in w["narrator-fields"].items():
        if key in narrator:
            out.append(f"- **{label}:** {narrator[key]}")
    pace = ", ".join(f"{w['bands'].get(band, band)}: {wpm}" for band, wpm in voice["pace"].items())
    out += [f"- {w['narrator-pace'].format(pace=pace)}", "", w["never"], ""]
    out += [f"- {rule}" for rule in narrator["avoid"]]
    return out + [""]


def _render_delivery(w: Words) -> list[str]:
    out = [f"## {w['delivery']}", ""]
    out += [f"- {rule}" for rule in w["delivery-rules"]]
    out += ["", w["tech-header"], "|---|---|"]
    out += [f"| {label} | {rule} |" for label, rule in w["tech"]]
    return out + [""]


def _render_cast(s: Story, w: Words, lang: str) -> list[str]:
    out = [f"## {w['who']}", "", w["who-intro"], ""]
    for c in s.cast(lang):
        if "personality" not in c and "pronounce" not in c:
            continue
        say = f" ({w['say'].format(pronounce=c['pronounce'])})" if c.get("pronounce") else ""
        line = f"- **{c.get('name', c['id'])}**{say}"
        if c.get("personality"):
            line += f": {c['personality']}"
        if c.get("refrain"):
            line += " " + w["refrain"].format(refrain=c["refrain"])
        out.append(line)
    return out + [""]


def _render_clip(s: Story, w: Words, lang: str, clip: Clip, narrator: dict, wpm: int) -> list[str]:
    story = s.text(lang)
    node = story["nodes"][clip.node] if clip.node else None
    found = s.delivered(lang, clip.id)
    kind_label = w["kinds"][clip.kind]
    if clip.kind == "page" and graph.kind(node) == graph.FORK:
        kind_label = w["page-fork"]
    elif clip.kind == "page" and graph.kind(node) == graph.ENDING:
        kind_label = w["page-ending"]
    out = [f"### {'✅' if found else '⬜'} `{clip.id}`: {kind_label}", ""]
    file = f"`{_rel(found)}`" if found else f"`{_rel(s.audio_dir(lang) / clip.id)}.wav` {w['file-or']}"
    out.append(f"- **{w['file']}:** {file}")

    directions = narrator["clips"]
    if clip.kind == "page":
        direction = directions["fork-page" if graph.kind(node) == graph.FORK else "page"]
        mood = s.mood(lang, node["image"])
        if mood:
            direction += " " + w["mood"].format(mood=mood)
    elif clip.kind == "question":
        a, b = (o["label"] for o in node["options"])
        direction = f"{directions['question']} {w['question'].format(a=a, b=b)}"
    elif clip.kind == "option":
        other = node["options"][1 - clip.option]["label"]
        direction = (f"{directions['option']} "
                     + w["option"].format(letter="AB"[clip.option], question=node["question"], other=other))
    elif clip.kind == "ending":
        kind = node["ending"]["kind"]
        direction = (f"{directions['ending']} "
                     + w["ending"].format(kind=w["ending-kinds"][kind], how=narrator["endingKinds"][kind]))
    else:
        direction = directions["title"]
    out.append(f"- **{w['direction']}:** {direction}")
    words = word_count(clip.script)
    out.append(f"- **{w['length']}:** " + w["length-value"].format(
        words=words, unit=w["word"][words != 1], duration=w.duration(seconds(clip.script, wpm))))
    out += [f"- **{w['script']}:**", "", _quote(clip.script), ""]
    return out


# Writing the files --------------------------------------------------------------------------------------------------

def _generated(path: Path) -> bool:
    return path.is_file() and path.read_text(encoding="utf-8").startswith(GENERATED)


def outputs() -> dict[Path, str | None]:
    """Every requests file and its text. None means a generated file to remove: a story that lost its text, a language
    it no longer has, or the single file each story had before narration was requested per language."""
    voice = load_json(VOICE)
    stories = [Story(STORIES / sid) for sid in story_ids() if _ready(sid)]
    out: dict[Path, str | None] = {REQUESTED_AUDIO: render(voice, stories)}
    for s in stories:
        for lang in s.requested(voice):
            out[s.requests_file(lang)] = render_story(s, lang, voice)
    for sid in story_ids():
        folder = STORIES / sid
        stale = [folder / FILE]  # where each story's one file lived before
        stale += sorted((folder / "audio").glob(f"*/{FILE}"))
        for path in stale:
            if path not in out and _generated(path):
                out[path] = None
    return out


def sync(check_only: bool = False) -> list[Path]:
    """Writes every requests file that changed (unless check_only) and returns the ones that were out of date."""
    changed = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        changed.append(path)
        if not check_only:
            if text is None:
                path.unlink()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    return changed


def write(check_only: bool = False) -> bool:
    """Writes the requests files. Returns True if they were all already up to date."""
    return not sync(check_only)
